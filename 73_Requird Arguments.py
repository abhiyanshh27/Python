# user defined functions (wiht argument)
def add(n1,n2):
    add = n1 + n2
    print(n1,"+",n2,"=",add)

def sub(n1,n2):
    sub = n1 - n2
    print(n1,"-",n2,"=",sub)

def mul(n1,n2):
    mul = n1 * n2
    print(n1,"*",n2,"=",mul)

def div(n1,n2):
    div = n1 / n2
    print(n1,"/",n2,"=",div)
